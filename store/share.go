package store

import (
	"context"
	"errors"
	"fmt"

	"github.com/aws/aws-sdk-go-v2/aws"
	"github.com/aws/aws-sdk-go-v2/service/dynamodb"
	"github.com/aws/aws-sdk-go-v2/service/dynamodb/types"
)

const condFailed = "ConditionalCheckFailed"

var (
	ErrInsufficient    = errors.New("insufficient collectibles")
	ErrRequestConflict = errors.New("requestID was already used with different details")
)

type ShareResult struct {
	// Duplicate is true when this requestID was already processed.
	Duplicate bool
}

// Share moves qty collectibles of type c from one user to another, exactly once per requestID.
// The requestID is generated by the client and reused on every retry of the same share.
//
// One transaction, five writes (about 10 write units):
//  1. idempotency record, only if the requestID is new
//  2. sender balance minus qty, only if the sender has at least qty
//  3. receiver balance plus qty
//  4. SHARE_SENT ledger entry for the sender
//  5. SHARE_RECEIVED ledger entry for the receiver
func (s *Store) Share(ctx context.Context, fromUser, toUser string, c Collectible, qty int64, requestID string) (ShareResult, error) {
	if fromUser == "" || toUser == "" || requestID == "" || fromUser == toUser || qty <= 0 || !isValid(c) {
		return ShareResult{}, ErrInvalidInput
	}

	now := s.now()
	nowUnix := now.Unix()
	ledgerSK := fmt.Sprintf("LEDGER#%019d#%s", now.UnixNano(), requestID)
	names := map[string]string{"#c": string(c)}

	_, err := s.db.TransactWriteItems(ctx, &dynamodb.TransactWriteItemsInput{
		TransactItems: []types.TransactWriteItem{
			{Put: &types.Put{
				TableName: &s.table,
				Item: map[string]types.AttributeValue{
					"PK":          str("REQ#" + requestID),
					"SK":          str("SHARE"),
					"fromUser":    str(fromUser),
					"toUser":      str(toUser),
					"collectible": str(string(c)),
					"qty":         num(qty),
					"expiresAt":   num(now.Add(idempotencyTTL).Unix()),
				},
				ConditionExpression: aws.String("attribute_not_exists(PK)"),
			}},
			{Update: &types.Update{
				TableName: &s.table,
				Key: map[string]types.AttributeValue{
					"PK": str("USER#" + fromUser),
					"SK": str("BALANCE"),
				},
				UpdateExpression:         aws.String("SET #c = #c - :n, updatedAt = :now"),
				ConditionExpression:      aws.String("#c >= :n"),
				ExpressionAttributeNames: names,
				ExpressionAttributeValues: map[string]types.AttributeValue{
					":n":   num(qty),
					":now": num(nowUnix),
				},
			}},
			{Update: &types.Update{
				TableName: &s.table,
				Key: map[string]types.AttributeValue{
					"PK": str("USER#" + toUser),
					"SK": str("BALANCE"),
				},
				UpdateExpression:         aws.String("ADD #c :n SET updatedAt = :now"),
				ExpressionAttributeNames: names,
				ExpressionAttributeValues: map[string]types.AttributeValue{
					":n":   num(qty),
					":now": num(nowUnix),
				},
			}},
			{Put: &types.Put{
				TableName: &s.table,
				Item: map[string]types.AttributeValue{
					"PK":           str("USER#" + fromUser),
					"SK":           str(ledgerSK),
					"kind":         str("SHARE_SENT"),
					"collectible":  str(string(c)),
					"qty":          num(qty),
					"counterparty": str(toUser),
					"requestId":    str(requestID),
					"createdAt":    num(nowUnix),
				},
			}},
			{Put: &types.Put{
				TableName: &s.table,
				Item: map[string]types.AttributeValue{
					"PK":           str("USER#" + toUser),
					"SK":           str(ledgerSK),
					"kind":         str("SHARE_RECEIVED"),
					"collectible":  str(string(c)),
					"qty":          num(qty),
					"counterparty": str(fromUser),
					"requestId":    str(requestID),
					"createdAt":    num(nowUnix),
				},
			}},
		},
	})
	if err == nil {
		return ShareResult{}, nil
	}

	codes, ok := cancelCodes(err)
	if !ok {
		return ShareResult{}, fmt.Errorf("share: %w", err)
	}
	if len(codes) > 0 && codes[0] == condFailed {
		return s.existingShare(ctx, fromUser, toUser, c, qty, requestID)
	}
	if len(codes) > 1 && codes[1] == condFailed {
		return ShareResult{}, ErrInsufficient
	}
	if code, retry := firstRetryable(codes); retry {
		return ShareResult{}, fmt.Errorf("%w: %s", ErrRetryable, code)
	}
	return ShareResult{}, fmt.Errorf("share: %w", err)
}

func (s *Store) existingShare(ctx context.Context, fromUser, toUser string, c Collectible, qty int64, requestID string) (ShareResult, error) {
	item, err := s.getRequest(ctx, requestID, "SHARE")
	if err != nil {
		return ShareResult{}, err
	}
	same := getS(item, "fromUser") == fromUser &&
		getS(item, "toUser") == toUser &&
		getS(item, "collectible") == string(c) &&
		getN(item, "qty") == qty
	if !same {
		return ShareResult{}, ErrRequestConflict
	}
	return ShareResult{Duplicate: true}, nil
}

// getRequest reads an idempotency record (REQ#<id> / <kind>).
func (s *Store) getRequest(ctx context.Context, requestID, kind string) (map[string]types.AttributeValue, error) {
	out, err := s.db.GetItem(ctx, &dynamodb.GetItemInput{
		TableName: &s.table,
		Key: map[string]types.AttributeValue{
			"PK": str("REQ#" + requestID),
			"SK": str(kind),
		},
		ConsistentRead: aws.Bool(true),
	})
	if err != nil {
		return nil, fmt.Errorf("reading idempotency record: %w", err)
	}
	if out.Item == nil {
		return nil, fmt.Errorf("idempotency record for %s missing after conflict", requestID)
	}
	return out.Item, nil
}

func isValid(c Collectible) bool {
	for _, v := range allCollectibles {
		if v == c {
			return true
		}
	}
	return false
}

// cancelCodes returns the per-item cancellation codes of a cancelled transaction,
// in the same order as the items were sent.
func cancelCodes(err error) ([]string, bool) {
	var tce *types.TransactionCanceledException
	if !errors.As(err, &tce) {
		return nil, false
	}
	codes := make([]string, len(tce.CancellationReasons))
	for i, r := range tce.CancellationReasons {
		codes[i] = aws.ToString(r.Code)
	}
	return codes, true
}

func firstRetryable(codes []string) (string, bool) {
	for _, code := range codes {
		if retryableCodes[code] {
			return code, true
		}
	}
	return "", false
}
